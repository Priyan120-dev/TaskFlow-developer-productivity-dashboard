/**
 * TaskFlow AI Copilot Branding Icon
 * Premium SaaS rounded-square badge featuring the official TaskFlow Copilot logo symbol.
 */
export const CopilotIcon = ({ size = 'md', className = '', variant = 'gradient' }) => {
  const sizeMap = {
    xs: 'w-4 h-4 rounded p-0.5',
    sm: 'w-5 h-5 rounded-md p-0.5',
    base: 'w-6 h-6 rounded-md p-1',
    md: 'w-8 h-8 rounded-lg p-1.5',
    lg: 'w-10 h-10 rounded-xl p-1.5',
    xl: 'w-12 h-12 rounded-2xl p-2',
  };

  const sizeClasses = sizeMap[size] || sizeMap.md;

  if (variant === 'light' || variant === 'white') {
    return (
      <div
        className={`inline-flex items-center justify-center bg-white shadow-md border border-slate-200/80 select-none flex-shrink-0 overflow-hidden ${sizeClasses} ${className}`}
        aria-label="TaskFlow Copilot"
      >
        <img
          src={copilotLogoDark}
          alt="TaskFlow Copilot"
          className="w-full h-full object-contain"
        />
      </div>
    );
  }

  return (
    <div
      className={`inline-flex items-center justify-center bg-gradient-to-tr from-purple-600 via-indigo-600 to-blue-600 shadow-sm shadow-purple-500/25 border border-white/20 select-none flex-shrink-0 overflow-hidden ${sizeClasses} ${className}`}
      aria-label="TaskFlow Copilot"
    >
      <img
        src={copilotLogoWhite}
        alt="TaskFlow Copilot"
        className="w-full h-full object-contain filter drop-shadow-[0_1px_2px_rgba(0,0,0,0.25)]"
      />
    </div>
  );
};

export const CopilotLogoSymbol = ({ className = 'w-6 h-6', variant = 'dark' }) => {
  const src =
    variant === 'white'
      ? copilotLogoWhite
      : variant === 'original'
      ? copilotLogoOriginal
      : copilotLogoDark;

  return (
    <img
      src={src}
      alt="TaskFlow Copilot Symbol"
      className={`object-contain select-none ${className}`}
    />
  );
};


